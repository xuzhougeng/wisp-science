#!/usr/bin/env python3
"""Export VectorDrawable resources from Wisp's single compose_icon source set."""
from pathlib import Path
import re
import shutil
import xml.etree.ElementTree as ET
from xml.sax.saxutils import quoteattr

ROOT = Path(__file__).resolve().parents[3]
DEST = ROOT / "apps/android/app/src/main/res/drawable"
ICONS = ("gear", "folder", "chevron-left", "chevron-right", "arrow-up",
         "notebook", "list", "research-trail", "square-pen", "chat", "calendar",
         "inbox", "camera", "edit", "book", "circle-help", "plus", "circle",
         "circle-check", "chevron-down", "image")


def path_data(element):
    a = element.attrib
    if element.tag == "path":
        return a["d"]
    if element.tag == "circle":
        x, y, r = (float(a[k]) for k in ("cx", "cy", "r"))
        return f"M{x-r},{y}a{r},{r} 0 1,0 {2*r},0a{r},{r} 0 1,0 {-2*r},0"
    if element.tag == "rect":
        x, y, w, h = (float(a[k]) for k in ("x", "y", "width", "height"))
        r = min(float(a.get("rx", "0")), w / 2, h / 2)
        return (f"M{x+r},{y}h{w-2*r}a{r},{r} 0 0,1 {r},{r}v{h-2*r}"
                f"a{r},{r} 0 0,1 {-r},{r}h{-w+2*r}a{r},{r} 0 0,1 {-r},{-r}"
                f"v{-h+2*r}a{r},{r} 0 0,1 {r},{-r}z")
    raise ValueError(f"Unsupported shared icon element: {element.tag}")


def main():
    source = (ROOT / "ui/src/app_support/messages.rs").read_text(encoding="utf-8")
    DEST.mkdir(parents=True, exist_ok=True)
    for name in ICONS:
        match = re.search(r'"' + re.escape(name) + r'" => view! \{ (.*?) \}\.into_view\(\)', source)
        if not match:
            raise ValueError(f"Missing compose_icon: {name}")
        paths = []
        for element in ET.fromstring("<svg>" + match[1] + "</svg>"):
            paths.append('    <path android:fillColor="@android:color/transparent" android:strokeColor="#FF000000"\n'
                         '        android:strokeWidth="2" android:strokeLineCap="round" android:strokeLineJoin="round"\n'
                         '        android:pathData=' + quoteattr(path_data(element)) + ' />')
        xml = ('<?xml version="1.0" encoding="utf-8"?>\n'
               '<!-- Generated by scripts/export_icons.py from compose_icon(); do not edit. -->\n'
               '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
               '    android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">\n'
               + "\n".join(paths) + '\n</vector>\n')
        (DEST / ("wisp_" + name.replace("-", "_") + ".xml")).write_text(xml, encoding="utf-8")
    brand = DEST.parent / "drawable-nodpi"
    brand.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(ROOT / "apps/ios/WispScience/Assets.xcassets/AppIcon.appiconset/AppIcon.png", brand / "wisp_app_icon.png")


if __name__ == "__main__":
    main()
